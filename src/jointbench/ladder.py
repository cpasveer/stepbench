"""The ladder: one front door to every test of StepBench.

A test is a setup (which fixed parts) at a level (which requirements). Version 1
(15 November 2026): three setups, six levels, each level the one below
plus one dimension:

    L1 fits       holes, seat inside, no collisions, every bolt turnable, clean
    L2 printable  + printed in PLA without support
    L3 strong     + a stated load (scored by printed weight)
    L4 assembles  + in through a small opening: two parts, bolted inside
    L5 locks      + the two parts join by push-and-turn, no key inside
    L6 moves      + a linkage on bearings carries the fixture into a latch

    `jointbench gen --setup pipe --level 4 --seed 7` writes that test's task.
    `jointbench ladder` prints which tests exist.

Seed 0 of every test is its public showcase (the setup's hand-picked look);
every other seed is a fresh random draw round it. The same seed gives the same
fixed parts at every level of a setup.

Each test is generated by a task family. ``WHERE`` maps a test to its family
and that family's own level number; a test that is planned but not built yet
maps to None. When a level lands on main, its line here is filled in.
"""
from __future__ import annotations

SETUPS = {
    "facing": "two facing plates",
    "flange": "a round flange and a block",
    "pipe": "a pipe and a square plate",
}
LEVELS = {1: "fits", 2: "printable", 3: "strong", 4: "assembles", 5: "locks", 6: "moves"}

# version 1: all six levels on all three setups (15 November 2026: 18 tests)
PLANNED = {(s, lv) for s in SETUPS for lv in LEVELS}

# test -> (family, the family's own level), or None while not built
WHERE: dict[tuple[str, int], tuple[str, int] | None] = {
    ("facing", 1): ("facing", 1), ("facing", 2): ("facing", 2), ("facing", 3): ("facing", 3),
    ("flange", 1): ("flange", 1), ("flange", 2): ("flange", 2), ("flange", 3): ("flange", 3),
    ("pipe", 1): ("pipe", 1), ("pipe", 2): ("pipe", 2), ("pipe", 3): ("pipe", 3),
    ("pipe", 4): ("pipe", 4), ("pipe", 5): ("pipe", 5),
    ("facing", 4): ("facing", 4), ("facing", 5): ("facing", 5),
    ("flange", 4): ("flange", 4), ("flange", 5): ("flange", 5),
    # level 6 (moves): one generator for every setup (``moves.l6``), the setup chosen by name
    ("facing", 6): None, ("flange", 6): ("moves", 6), ("pipe", 6): None,
}
SHOWCASE_SEED = 0


class NotBuilt(LookupError):
    pass


def resolve(setup: str, level: int) -> tuple[str, int]:
    """(family, family level) for a test; NotBuilt if it is not available (yet)."""
    if setup not in SETUPS:
        raise NotBuilt(f"no setup {setup!r}; the setups are {', '.join(SETUPS)}")
    if level not in LEVELS:
        raise NotBuilt(f"no level {level}; the levels are 1-6")
    if (setup, level) not in PLANNED:
        raise NotBuilt(f"{setup} L{level} ({LEVELS[level]}) is not part of version 1")
    where = WHERE.get((setup, level))
    if where is None:
        raise NotBuilt(f"{setup} L{level} ({LEVELS[level]}) is planned for version 1 but not built yet")
    return where


def table() -> str:
    """Which tests exist: built, coming (planned, not built yet), or not in version 1."""
    rows = [f"{'':10}" + "".join(f"L{lv} {LEVELS[lv]:<11}" for lv in LEVELS)]
    for s in SETUPS:
        cells = []
        for lv in LEVELS:
            if (s, lv) not in PLANNED:
                cells.append("-")
            elif WHERE.get((s, lv)) is None:
                cells.append("coming")
            else:
                cells.append("built")
        rows.append(f"{s:10}" + "".join(f"{c:<14}" for c in cells))
    rows.append("")
    rows.append("seed 0 = the public showcase; any other seed = a fresh random task")
    return "\n".join(rows)
